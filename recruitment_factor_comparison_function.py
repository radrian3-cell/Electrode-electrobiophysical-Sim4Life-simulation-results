import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path


df = pd.read_csv("my_data_ - Sheet19 (1).csv")

df.columns = (df.columns.str.strip().str.replace("–", "-", regex=False))

print(df.columns.tolist())


comparisons = [('Fascicle (3:1) Parallel (0.9+0.5)','Fascicle (3:1) Parallel (0.9+0.5) Cathode First')]


output_dir5 = Path("Titration_Factor_Plots_0_to_05")
output_dir5.mkdir(exist_ok=True)

output_dir1 = Path("Titration_Factor_Plots_0_to_01")
output_dir1.mkdir(exist_ok=True)


def graph_maker(size,extra,spacing):
  for x_col, y_col in comparisons:

      fig, ax = plt.subplots(figsize=(8, 8))

      ax.scatter(df[x_col],df[y_col],s=180,color="#ED7D31",label="Titration Factor")
      ax.plot([0, size],[0, size],linestyle=":",linewidth=3,color="#0B2E59")
      ax.set_xlim(0, size)
      ax.set_ylim(0, size)
      ticks = np.arange(0, spacing, extra)
      ax.set_xticks(ticks)
      ax.set_yticks(ticks)
      ax.set_xlabel(x_col, fontsize=22)
      ax.set_ylabel(y_col, fontsize=22)
      ax.set_title(f"Titration Factor ({x_col} vs {y_col})",fontsize=30,pad=30)
      ax.legend(loc="upper center",bbox_to_anchor=(0.5, 0.92),frameon=False,fontsize=18)
      ax.set_aspect('equal', adjustable='box')
      ax.tick_params(axis='both', labelsize=16)

      for spine in ax.spines.values():
          spine.set_linewidth(1.5)

      plt.tight_layout()

      filename = (f"{x_col.replace(' ','_').replace('-','')}"f"_vs_"f"{y_col.replace(' ','_').replace('-','')}"f"_[0-{size}].png")
      if size == 1:
        plt.savefig(output_dir1 / filename,dpi=300,bbox_inches="tight")
      else:
        plt.savefig(output_dir5 / filename,dpi=300,bbox_inches="tight")
      plt.show()
      plt.close()


graph_maker(5,1,6)
graph_maker(1,.1,1.1)
print(f"\nFinished! Generated {2*len(comparisons)} plots.")

